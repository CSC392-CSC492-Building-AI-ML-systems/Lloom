import Link from "next/link";
import { allDocumentsSlice, getMatrixCounts } from "@/fixtures/run-results";
import type { ConceptCounts, DatasetSlice, RunResults } from "@/fixtures/run-results";

export default function ConceptMatrix({
    results,
    rows,
    groupingId,
    onGroupingChange,
    getConceptHref,
    onConcept,
    onCell,
}: {
    results: RunResults;
    rows: ConceptCounts[];
    groupingId: string;
    onGroupingChange: (id: string) => void;
    getConceptHref: (row: ConceptCounts, slice?: DatasetSlice) => string;
    onConcept: (row: ConceptCounts) => void;
    onCell: (row: ConceptCounts, slice: DatasetSlice, count: number) => void;
}) {
    const grouping = results.groupings.find((item) => item.id === groupingId);
    const slices = [allDocumentsSlice, ...(grouping?.slices ?? [])];
    const counts = getMatrixCounts(results, rows, slices);
    const maximum = Math.max(1, ...counts.flat());
    return (
        <section
            aria-labelledby="concept-matrix-heading"
            className="min-w-0 rounded-[14px] border border-outline bg-surface p-5 md:p-6"
        >
            <div className="flex flex-wrap items-center justify-between gap-4">
                <h2
                    id="concept-matrix-heading"
                    className="border-l-[3px] border-primary pl-2.5 text-xl font-medium text-primary"
                >
                    Concept Matrix
                </h2>
                <div>
                    <label
                        htmlFor="result-grouping"
                        className="block text-[13px] text-content-secondary"
                    >
                        Group by dataset column
                    </label>
                    <select
                        id="result-grouping"
                        value={groupingId}
                        onChange={(event) => onGroupingChange(event.target.value)}
                        className="mt-1 min-h-11 min-w-[184px] max-w-full rounded-[8px] border border-outline bg-surface px-3 text-[15px] focus-visible:outline-2 focus-visible:outline-primary"
                    >
                        <option value="all">All Documents</option>
                        {results.groupings.map((item) => (
                            <option key={item.id} value={item.id}>
                                {item.label}
                            </option>
                        ))}
                    </select>
                </div>
            </div>
            <p className="mt-3 text-[15px] text-content-secondary">
                Compare concept matches across different subsets of your dataset.
            </p>
            <p className="mt-3 text-[13px] text-content-secondary">
                Rows represent concepts and Outlier; columns represent dataset slices. Bubble area
                indicates matching document counts.
            </p>
            <p className="mt-3 text-[13px] text-content-secondary">
                {grouping?.provenance === "synthetic"
                    ? "Likes is synthetic preview metadata, not a field in the existing dataset fixture or an attribute generated by LLooM."
                    : "All documents are shown. This fixture has no additional grouping metadata selected."}
            </p>
            <div
                role="region"
                aria-label="Concept matrix"
                tabIndex={0}
                className="mt-4 overflow-x-auto rounded focus-visible:outline-2 focus-visible:outline-primary"
            >
                <table className="w-full min-w-[650px] table-fixed border-collapse">
                    <caption className="sr-only">
                        Exact matching document counts by concept and dataset slice
                    </caption>
                    <thead>
                        <tr>
                            <th scope="col" className="w-[180px] md:w-[300px]">
                                <span className="sr-only">Concept</span>
                            </th>
                            {slices.map((slice) => (
                                <th
                                    key={slice.id}
                                    scope="col"
                                    className="w-[180px] border-l border-outline px-3 py-4 text-center text-[13px] font-normal text-content-secondary"
                                >
                                    {slice.label}
                                </th>
                            ))}
                        </tr>
                    </thead>
                    <tbody>
                        {rows.map((row, index) => (
                            <tr key={row.id} className="odd:bg-surface-subtle">
                                <th
                                    scope="row"
                                    className="px-4 py-2 text-left text-[15px] font-normal"
                                >
                                    {row.kind === "concept" ? (
                                        <Link
                                            href={getConceptHref(row)}
                                            className="inline-flex min-h-11 items-center rounded text-left text-primary hover:underline focus-visible:outline-2 focus-visible:outline-primary"
                                        >
                                            {row.name}
                                        </Link>
                                    ) : (
                                        <button
                                            type="button"
                                            onClick={() => onConcept(row)}
                                            className="min-h-11 rounded text-left text-primary hover:underline focus-visible:outline-2 focus-visible:outline-primary"
                                        >
                                            {row.name}
                                        </button>
                                    )}
                                </th>
                                {slices.map((slice, column) => {
                                    const count = counts[index][column];
                                    const radius = count ? 27 * Math.sqrt(count / maximum) : 0;
                                    return (
                                        <td
                                            key={slice.id}
                                            className="border-l border-outline text-center"
                                        >
                                            {row.kind === "concept" ? (
                                                <Link
                                                    href={getConceptHref(row, slice)}
                                                    aria-label={`${row.name}, ${slice.label}: ${count} matching documents`}
                                                    title={`${count} matching documents`}
                                                    className="inline-flex min-h-16 min-w-16 items-center justify-center rounded focus-visible:outline-2 focus-visible:outline-primary"
                                                >
                                                    {" "}
                                                    <svg
                                                        aria-hidden="true"
                                                        width="60"
                                                        height="60"
                                                        viewBox="0 0 60 60"
                                                    >
                                                        <circle
                                                            cx="30"
                                                            cy="30"
                                                            r={radius}
                                                            className="fill-brand-light"
                                                        />
                                                        {!count && (
                                                            <text
                                                                x="30"
                                                                y="35"
                                                                textAnchor="middle"
                                                                className="fill-content-secondary text-[13px]"
                                                            >
                                                                0
                                                            </text>
                                                        )}
                                                    </svg>
                                                </Link>
                                            ) : (
                                                <button
                                                    type="button"
                                                    aria-label={`Outlier, ${slice.label}: ${count} documents`}
                                                    title={`${count} documents`}
                                                    onClick={() => onCell(row, slice, count)}
                                                    className="inline-flex min-h-16 min-w-16 items-center justify-center rounded focus-visible:outline-2 focus-visible:outline-primary"
                                                >
                                                    {" "}
                                                    <svg
                                                        aria-hidden="true"
                                                        width="60"
                                                        height="60"
                                                        viewBox="0 0 60 60"
                                                    >
                                                        <circle
                                                            cx="30"
                                                            cy="30"
                                                            r={radius}
                                                            className="fill-brand-light"
                                                        />
                                                        {!count && (
                                                            <text
                                                                x="30"
                                                                y="35"
                                                                textAnchor="middle"
                                                                className="fill-content-secondary text-[13px]"
                                                            >
                                                                0
                                                            </text>
                                                        )}
                                                    </svg>
                                                </button>
                                            )}
                                        </td>
                                    );
                                })}
                            </tr>
                        ))}
                    </tbody>
                </table>
            </div>
            <p className="mt-4 text-center text-[13px] text-content-secondary">
                Bubble area indicates match volume. Focus or hover a bubble for its exact count.
            </p>
            <p className="mt-5 text-[13px] text-content-secondary">
                Select a concept name or bar for details. Select a bubble for matching documents.
                Document Details and Outlier Details are not implemented yet.
            </p>
        </section>
    );
}
